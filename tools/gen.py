def drawn(cfg, v, offset=0, axis=0):
    """Where the game draws a rects' px value (axis 0 x, 1 y) on the rows - anchored, as all the
    rows' pieces are, to the screen's bottom-centre by whole-unit constants - `offset` more
    units in (a piece on it): its constant run from the exact point (the constants are offsets
    from it rounded), then the whole pixel, .5 rounding down (23_42_43, the plates' fountains)."""
    u = Units(cfg)
    pos = POS[BOTTOM_CENTRE[axis]]
    size = (cfg["screen"]["width"], cfg["screen"]["height"])[axis]
    at = size * pos + (u(v) - round(screen_units(cfg)[axis] * pos) + offset) / u.scale
    return math.ceil(round(at, 6) - 0.5)


def fountain_lines(cfg, team, n, pts, box, seams, half, end_half):
    """The row frame's slanted lines beside the fountains moved so each lies [row_frame]
    fountain_gap px across the slant from its fountain's frame, as the game draws both: the
    plates are 135.9 px apart, so each fountain lands on another fraction of a pixel, and the
    frame's own texture lands ~1 px off and 1 px wider (its constants and pixels rounded). At
    the exact places blue's outer two plates and red's had ~1 px more black by the fountain than
    the other three (23_42_43, the user's "blackspace"; the teams the same).
    Blue's fountains are at their plates' left: plate i's line the outer end (i = 0) or seam
    i - 1; red's at the right: seam i, or the outer end (the last). The inner ends have none.
    Returns pts and seams, moved."""
    row, cell, px = cfg["hero_row"], HeroCell(cfg), 1 / Units(cfg).scale
    gap = float(cfg["row_frame"]["fountain_gap"])
    across = math.hypot(1, cell.lean)                  # across the slant -> along a row
    (l, t, r, b), _ = fountain_rect(cfg, team)
    ax, ay, aw, ah = SLOT_ART
    cut = SLOT_LEAN * ah
    # the art's bottom corner on the line's side, slot units (slot_inside: red's leans /, blue's
    # mirrored); the line's side of the plate: blue's left, red's right
    corner = SLOT_W - ax - aw + cut if team == "blue" else ax + aw - cut
    side = -1 if team == "blue" else 1
    # the texture's rect as drawn, and drawn -> its own px
    bx, by, bw, bh = box
    tl, tr = drawn(cfg, bx), drawn(cfg, bx + bw)
    tt, tb = drawn(cfg, by, axis=1), drawn(cfg, by + bh, axis=1)
    left = row["blue_left"] + (5 - n) * cell.pitch * px if team == "blue" else row["red_left"]
    at = lambda line, y: line[0][0] + (line[1][0] - line[0][0]) * (y - line[0][1]) / (line[1][1] - line[0][1])
    ends = (0, 3) if team == "blue" else (1, 2)
    lines = [(pts[ends[0]], pts[ends[1]])] + list(seams) if team == "blue" else list(seams) + [(pts[1], pts[2])]
    moves = []
    for i, line in enumerate(lines[:n]):
        c = round(left + i * cell.pitch * px, 1)          # as rects' hero_ cells
        fl, fr = drawn(cfg, c, l), drawn(cfg, c, r)
        ft, fb = drawn(cfg, row["top"], t, 1), drawn(cfg, row["top"], b, 1)
        x = fl + corner / SLOT_W * (fr - fl)
        y = ft + (ay + ah) / SLOT_H * (fb - ft)
        w = end_half if i == (0 if team == "blue" else n - 1) else half   # the outer end's, or a seam's
        x += side * (gap + w) * across                    # the line's middle, as drawn
        x, y = bx + (x - tl) * bw / (tr - tl), by + (y - tt) * bh / (tb - tt)   # in the texture's px
        moves.append(x - at(line, y))
    end = moves.pop(0) if team == "blue" else moves.pop()
    pts = [(x + end, y) if k in ends else (x, y) for k, (x, y) in enumerate(pts)]
    seams = tuple(((x1 + d, y1), (x2 + d, y2)) for ((x1, y1), (x2, y2)), d in zip(seams, moves))
    return pts, seams


@functools.lru_cache(maxsize=None)
def _row_frame_dds(pts, box, outset, inside, k, rim, seams=(), seam=0.0, rules=(), end_inside=None):
    """row_frame_texture's drawing (cached: the textures are asked for several times a run).
    The distance outside is the true one, so the outside corners come out rounded: a mitred
    corner (convex_sdf's) on the plates' sharp slant pokes out about twice the width. Each
    edge of the line ramps over one texel inside it, so the anti-aliasing stays in the rect.
    seams: lines ((top x, y), (bottom x, y)), `seam` px wide centred on each, cut flat at
    their ends' heights; rules: heights of lines straight across, `seam` px wide too.
    end_inside: how far the line reaches over the plates along the row's two slanted ends
    (`inside` elsewhere); the outer side and the outset stay. Only the bands along the outline,
    the seams and the rules are worked out; the rest is clear."""
    end_inside = inside if end_inside is None else end_inside
    x0, y0, bw, bh = box
    w, h = round(bw * k), round(bh * k)
    n = len(pts)
    planes, segs = [], []
    cx, cy = sum(p[0] for p in pts) / n, sum(p[1] for p in pts) / n
    for i in range(n):
        (x1, y1), (x2, y2) = pts[i], pts[(i + 1) % n]
        ln = math.hypot(x2 - x1, y2 - y1)
        nx, ny = (y2 - y1) / ln, -(x2 - x1) / ln
        if nx * (cx - x1) + ny * (cy - y1) > 0:
            nx, ny = -nx, -ny
        planes.append((nx, ny, nx * x1 + ny * y1))
        segs.append((x1, y1, x2 - x1, y2 - y1, ln * ln))

    # the inner side's distance: the slanted ends' planes (edges 1 and 3: TR-BR, BL-TL) moved
    # in by the difference, so the line reaches end_inside over the plates there
    grow = tuple(end_inside - inside if i % 2 else 0.0 for i in range(n))

    def dist_in(x, y):
        return max(nx * x + ny * y - c + g for (nx, ny, c), g in zip(planes, grow))

    def dist(x, y):
        d = max(nx * x + ny * y - c for nx, ny, c in planes)
        if d <= 0:
            return d
        best = d * d * 4 + 1e9
        for sx, sy, dx, dy, l2 in segs:
            t = max(0.0, min(1.0, ((x - sx) * dx + (y - sy) * dy) / l2))
            ex, ey = x - sx - t * dx, y - sy - t * dy
            best = min(best, ex * ex + ey * ey)
        return math.sqrt(best)

    clamp = lambda v: 0.0 if v < 0 else 1.0 if v > 1 else v
    rgb = lambda hx: tuple(int(hx[i:i + 2], 16) / 255 for i in (0, 2, 4))
    chrome = list(zip((0, .35, .6, 1), (rgb(c) for c in rim)))

    def colour(t):
        for (o1, c1), (o2, c2) in zip(chrome, chrome[1:]):
            if t <= o2:
                f = (t - o1) / (o2 - o1)
                return tuple(p + (q - p) * f for p, q in zip(c1, c2))
        return chrome[-1][1]

    # each seam as (x at y, across distance -> perpendicular, its top, its bottom)
    lines = []
    for (sx1, sy1), (sx2, sy2) in seams:
        run = (sx2 - sx1) / (sy2 - sy1)
        lines.append((lambda y, sx1=sx1, sy1=sy1, run=run: sx1 + run * (y - sy1), 1 / math.hypot(1, run), sy1, sy2))
    half = seam / 2

    (ax, top), (_, _), (_, bottom), (bx, _) = pts[0], pts[1], pts[2], pts[3]
    edge = pts[1][0] - pts[0][0]
    reach = outset + max(inside, end_inside) + 2 / k
    span = lambda a, b: (max(0, int((a - x0) * k)), min(w, int((b - x0) * k) + 1))
    rows = []
    for ty in range(h):
        y = y0 + (ty + 0.5) / k
        row = bytearray(4 * w)
        c = colour(clamp((y - y0) / bh))
        here = [(at, perp) for at, perp, s1, s2 in lines if s1 <= y <= s2]
        if y - top < reach or bottom - y < reach or any(abs(y - r) < half + 2 / k for r in rules):
            spans = [(0, w)]
        else:
            lx = ax + (bx - ax) * (y - top) / (bottom - top)
            spans = [span(lx - reach, lx + reach), span(lx + edge - reach, lx + edge + reach)]
            spans += [span(at(y) - half - 2 / k, at(y) + half + 2 / k) for at, _ in here]
        for a, b in spans:
            for tx in range(a, b):
                x = x0 + (tx + 0.5) / k
                d = dist(x, y)
                cover = clamp((outset - d) * k) * clamp(((dist_in(x, y) if d < 0 else d) + inside) * k)
                if d < 0:
                    for at, perp in here:
                        cover = max(cover, clamp((half - abs(x - at(y)) * perp) * k))
                    for r in rules:
                        cover = max(cover, clamp((half - abs(y - r)) * k))
                if cover > 0:
                    row[4 * tx:4 * tx + 4] = bytes((round(c[2] * 255), round(c[1] * 255), round(c[0] * 255), round(cover * 255)))
        rows.append(bytes(row))
    return dds_bgra(w, h, b"".join(rows))


def bar_texture_size(cfg, w, h):
    """A slanted bar texture at its size on a 1440p screen (w x h: layout.toml px; ART_HEIGHT).
    Our DDS files carry no mipmaps, so a texture drawn much smaller than it is gets sampled
    coarsely and its slanted edge steps: the core bar (213 x 24 px) from a 512 x 32 texture
    (powers of two, rounded up) read "ragged" in game (2026-09-30). 1440p's size is drawn at
    75% at 1080p, which doesn't."""
    k = art_scale(cfg)
    return math.ceil(w * k), math.ceil(h * k)


def slant_bars(cfg):
    """Every generated texture but the portrait masks (bars, plate hit areas, the top
    backplate), by constant name: {name: (file name, dds bytes)}. Names
    carry a content hash (textures are cached by path across replay reloads)."""
    rects_ = team_bar_rects(cfg)
    lean = HeroCell(cfg).lean
    xp, core = cfg["team_xp"], cfg["team_core"]
    out = {}
    # The bars' fills are STRETCHED to the value (seen in game, 2026-09-29: a draining core's
    # slanted ends squashed toward vertical), so a fill is a plain block of colour and the
    # slant comes from a mask over the bar (mask frames, AlphaMaskSiblings). Tracks don't
    # move, so they keep the slant in their own texture.
    for team in ("blue", "red"):
        for bar, spec, fill in (("xp", xp, xp["colour"]), ("core", core, core[f"{team}_colour"])):
            (_, _, w, h), _ = rects_[f"{team}_{bar}"]
            cut = lean * h / w
            size = bar_texture_size(cfg, w, h)
            for part, data in (("fill", slant_texture(team, 0, fill, size=(32, 32))),
                               ("track", slant_texture(team, cut, spec["track_colour"], spec["track_alpha"], size=size)),
                               ("mask", slant_texture(team, cut, "ffffff", size=size))):
                digest = hashlib.sha1(data).hexdigest()[:8]
                out[name(bar, part, team)] = (f"FCJH_Bar_{bar}_{part}_{team}_{digest}.dds", data)
        # the core bar's own chrome line ([team_core] frame_width)
        data = core_chrome_texture(cfg, team)
        digest = hashlib.sha1(data).hexdigest()[:8]
        out[name("core", "chrome", team)] = (f"FCJH_CoreChrome_{team}_{digest}.dds", data)
        # XP for rows of 1-4 heroes: a shorter bar keeps the same slant only with its own cut
        for n in range(1, 5):
            (_, _, w, h), _ = team_bar_rects(cfg, n)[f"{team}_xp"]
            for part, colour, alpha in (("mask", "ffffff", 255), ("track", xp["track_colour"], xp["track_alpha"])):
                data = slant_texture(team, lean * h / w, colour, alpha, size=bar_texture_size(cfg, w, h))
                digest = hashlib.sha1(data).hexdigest()[:8]
                out[name("xp", part, team, f"n{n}")] = (f"FCJH_Bar_xp_{part}_{team}_n{n}_{digest}.dds", data)
        # the row frame round the plates and the XP bar ([row_frame]), for rows of 1-5
        for n in range(1, 6):
            data = row_frame_texture(cfg, team, n)
            digest = hashlib.sha1(data).hexdigest()[:8]
            out[name("row", "frame", team, *([] if n == 5 else [f"n{n}"]))] = (f"FCJH_RowFrame_{team}_n{n}_{digest}.dds", data)
    # the top bar's backplate behind Blizzard's hexagon (layout.toml [top_backplate])
    data = top_backplate_texture(cfg)
    digest = hashlib.sha1(data).hexdigest()[:8]
    out[name("top", "backplate")] = (f"FCJH_TopBackplate_{digest}.dds", data)
    cell = HeroCell(cfg)
    # the plate's own shape, as the click target's hit-test texture: plates overlap along the
    # slant, and a square click area sent clicks on one plate's corner to its neighbour
    for team in ("blue", "red"):
        tw, th = plate_art_sizes(cfg)["cell"]
        data = bytearray(slant_texture(team, cell.overlap / cell.w, "ffffff", size=(tw, th)))
        # ...with the heroic icon cut away: a click there is for the heroic's tooltip
        # (talent_row_lifts), not a hero select
        l, t, r, b = heroic_icon_rect(cfg, team)
        for ty in range(round(t / cell.h * th), min(th, round(b / cell.h * th))):
            for tx in range(round(l / cell.w * tw), round(r / cell.w * tw)):
                data[128 + (ty * tw + tx) * 4 + 3] = 0
        data = bytes(data)
        digest = hashlib.sha1(data).hexdigest()[:8]
        out[name("plate", "hit", team)] = (f"FCJH_PlateHit_{team}_{digest}.dds", data)
    return out


