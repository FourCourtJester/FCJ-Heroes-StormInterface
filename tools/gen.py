def portrait_mask_file(team):
    # Heroes caches a texture by its path across replay reloads (layouts reload, textures
    # don't), so every version of a mask gets its own name: a hash of its content.
    digest = hashlib.sha1(portrait_mask(team)).hexdigest()[:8]
    return f"FCJH_Portrait_{team}_{digest}.dds"


@functools.cache
def portrait_mask(team, size=(256, 128), sub=4):
    """The portrait cut to the in-game cell's parallelogram, as an alpha mask.

    Blizzard's own ImageMaskTexture follows the portrait's TextureCoords, so cropping the
    observer's wide portrait art to its face also crops away the mask's left-edge cut (red
    portraits spilled over their neighbours). An AlphaMaskTexture spans the frame instead.
    Worked in native cell units, so it holds at any scale: the plate leans OVERLAP across
    its full height H - blue \\ (top edge on the left), red / (top edge on the right)."""
    w, h = size
    c = HeroCell
    top, bottom = -1, c.PORTRAIT_H - 1  # the portrait frame, in cell units
    # the portrait runs 2 units below the bar backings; Blizzard's art hides that strip,
    # ours showed the hero under the resource bar - so stop where the backing does
    # (1 unit early, so the mask's soft edge lands under the backing, not a hairline below it)
    cut = c.BLUE["health_backing"][3] - 1

    def left_edge(y):
        down = y / c.H
        return c.OVERLAP * (down if team == "blue" else 1 - down)

    rows = []
    for ty in range(h):
        row = bytearray()
        for tx in range(w):
            x0, x1 = tx / w * c.W, (tx + 1) / w * c.W
            cover = 0.0
            for s in range(sub):
                y = top + (ty + (s + 0.5) / sub) / h * (bottom - top)
                if y > cut:
                    continue
                left = left_edge(y) + c.BORDER
                right = left_edge(y) + c.W - c.OVERLAP - c.BORDER
                cover += max(0.0, min(x1, right) - max(x0, left)) / (x1 - x0)
            a = round(255 * cover / sub)
            row += bytes((a, a, a, a))  # B, G, R, A: grey = alpha, whichever the engine reads
        rows.append(bytes(row))
    return dds_bgra(w, h, b"".join(rows))


def slant_texture(team, cut, colour, alpha=255, size=(512, 32), sub=4):
    """A solid-colour parallelogram: the team's lean, cut `cut` of the width in (the slant's
    horizontal run over the bar's height, as a fraction of its width). Blue leans \\ (top edge
    flush left), red / (top edge flush right)."""
    w, h = size
    r, g, b = bytes.fromhex(colour)
    rows = []
    for ty in range(h):
        row = bytearray()
        for tx in range(w):
            cover = 0.0
            for s in range(sub):
                down = (ty + (s + 0.5) / sub) / h          # 0 at the top, 1 at the bottom
                shift = cut * (down if team == "blue" else 1 - down)
                left, right = shift * w, (1 - cut + shift) * w
                cover += max(0.0, min(tx + 1, right) - max(tx, left))
            row += bytes((b, g, r, round(alpha * cover / sub)))
        rows.append(bytes(row))
    return dds_bgra(w, h, b"".join(rows))


def hex_fade_texture(team, colour, alpha, hex_px, box_px, size=(256, 128)):
    """A flat-topped hexagon lattice in one colour, outlines bright and cells faint, fading to
    nothing away from the screen centre (leftward on blue, rightward on red). box_px is the
    backdrop's size on screen, hex_px the hexagons' width there; the texture (a power of two)
    is stretched onto that box, so the lattice is drawn in box coordinates."""
    import math
    w, h = size
    sx, sy = box_px[0] / w, box_px[1] / h        # texel -> screen px
    R = hex_px / 2                              # circumradius, screen px
    r3 = math.sqrt(3)
    red, green, blue = bytes.fromhex(colour)
    line = 0.12                                 # outline thickness, fraction of R
    rows = []
    for ty in range(h):
        row = bytearray()
        for tx in range(w):
            x, y = (tx + 0.5) * sx, (ty + 0.5) * sy
            # nearest hex centre in a flat-topped axial grid
            q = (2 / 3 * x) / R
            rr = (-1 / 3 * x + r3 / 3 * y) / R
            cx, cz = q, rr
            cy = -cx - cz
            rx, ry, rz = round(cx), round(cy), round(cz)
            dx, dy, dz = abs(rx - cx), abs(ry - cy), abs(rz - cz)
            if dx > dy and dx > dz:
                rx = -ry - rz
            elif dy > dz:
                ry = -rx - rz
            else:
                rz = -rx - ry
            hx, hy = R * 1.5 * rx, R * r3 * (rz + rx / 2)
            ox, oy = abs(x - hx), abs(y - hy)
            edge = max(oy / (r3 / 2 * R), (ox + oy / r3) / R)    # 0 centre .. 1 edge
            cell = 1.0 if edge > 1 - line else 0.28
            t = tx / (w - 1)
            fade = (t if team == "blue" else 1 - t) ** 1.6
            row += bytes((blue, green, red, round(alpha * cell * fade)))
        rows.append(bytes(row))
    return dds_bgra(w, h, b"".join(rows))


def bar_texture_size(w, h):
    """A slanted bar texture close to its size on screen (w x h px), in powers of two. Our
    DDS files carry no mipmaps, so a texture drawn much smaller than it is gets sampled
    coarsely and its slanted edge steps: the core bar (213 x 24 px) from a 512 x 32
    texture read "ragged" in game (2026-09-30)."""
    p2 = lambda v: 1 << max(4, (round(v) - 1).bit_length())
    return p2(w), p2(h)


def slant_bars(cfg):
    """Every slanted texture (bars and plate tokens), by constant name: {name: (file name, dds bytes)}. Names
    carry a content hash (textures are cached by path across replay reloads)."""
    rects_ = team_bar_rects(cfg)
    lean = HeroCell(cfg).overlap / HeroCell(cfg).h
    xp, core = cfg["team_xp"], cfg["team_core"]
    out = {}
    # The bars' fills are STRETCHED to the value (seen in game, 2026-09-29: a draining core's
    # slanted ends squashed toward vertical), so a fill is a plain block of colour and the
    # slant comes from a mask over the bar (mask frames, AlphaMaskSiblings). Tracks don't
    # move, so they keep the slant in their own texture.
    for team in ("blue", "red"):
        for bar, spec, fill in (("xp", xp, xp["colour"]), ("core", core, core[f"{team}_colour"])):
            (_, _, w, h), _ = rects_[f"{team}_{bar}"]
            cut = lean * h / w
            size = bar_texture_size(w, h)
            for part, data in (("fill", slant_texture(team, 0, fill, size=(32, 32))),
                               ("track", slant_texture(team, cut, spec["track_colour"], spec["track_alpha"], size=size)),
                               ("mask", slant_texture(team, cut, "ffffff", size=size))):
                digest = hashlib.sha1(data).hexdigest()[:8]
                out[name(bar, part, team)] = (f"FCJH_Bar_{bar}_{part}_{team}_{digest}.dds", data)
