    x0, y0, x1, y1 = MASK_BOX
    rows = []
    for ty in range(h):
        row = bytearray()
        for tx in range(w):
            n = 0
            for sy in range(sub):
                for sx in range(sub):
                    x = x0 + (tx + (sx + 0.5) / sub) / w * (x1 - x0)
                    y = y0 + (ty + (sy + 0.5) / sub) / h * (y1 - y0)
                    n += slot_inside(SLOT_W - x if team == "blue" else x, y) >= SLOT_RIM / 2
            a = round(255 * n / sub ** 2)
            row += bytes((a, a, a, a))
        rows.append(bytes(row))
    return dds_bgra(w, h, b"".join(rows))


