def layout_order(layout_dir, extra=(), generated=None):
    """Constants first, then the rest by name (including generated layouts, whether or not
    they exist on disk yet), then extras (dev layouts) last."""
    generated = GENERATED_LAYOUTS if generated is None else generated
    names = {p.name for p in layout_dir.glob("*.StormLayout")} | set(generated)
    names -= {INDEX_FILE, CONSTANTS_FILE}
    return [CONSTANTS_FILE] + sorted(names) + list(extra)


# Exempt from [screen] padding: the top bar, centred on the top edge; Blizzard's minimap,
# whose square hangs off the bottom by design ([minimap] bottom); and Blizzard's kill feed,
# left where Blizzard puts it.
PADDING_EXEMPT = {"blue_score", "blue_name", "blue_logo", "blue_level", "blue_talent_lead", "blue_bans",
                  "division", "logo_plate", "clock", "red_level", "red_talent_lead", "red_logo", "red_name",
                  "red_score", "red_bans", "game_count", "top_backplate", "minimap", "kill_feed",
                  # the replay box's tab sits flush in the top-right corner; the box itself
                  # keeps the padding (user, 2026-10-16)
                  "replay_collapsed"}


def check_padding(cfg):
    """Nothing closer to a screen edge than [screen] padding (user, 2026-10-05)."""
    pad = cfg["screen"].get("padding")
    if pad is None:
        return
    sw, sh = cfg["screen"]["width"], cfg["screen"]["height"]
    # an element's `art_inset`: its art draws that far inside its frame - the padding is
    # measured to the art, which is what's seen
    inset = lambda stem: cfg.get("element", {}).get(stem, {}).get("art_inset", 0)
    close = [f"{stem} {x, y, w, h}" for stem, ((x, y, w, h), _) in rects(cfg).items()
             if stem not in PADDING_EXEMPT and min(x, y, sw - x - w, sh - y - h) + inset(stem) < pad - 0.05]
    if close:
        raise SystemExit(f"closer to the screen's edge than [screen] padding = {pad} px: " + "; ".join(close))


def committed_files(cfg, source=SOURCE):
    """{path under source: bytes} for every generated file that lives in the repo."""
    layout_dir = source / LAYOUT_REL
    # the inspect card is laid out to a size of its own (inspect_card W x H, cut to what it
    # holds); its box in layout.toml must be that size
    (_, _, iw, ih), _ = rects(cfg)["inspect"]
    u = Units(cfg)
    if (round(u(iw)), round(u(ih))) != (inspect_card.W, inspect_card.H):
        raise SystemExit(f"layout.toml element.inspect is {iw} x {ih} px ({u(iw)} x {u(ih)} units); "
                         f"tools/inspect_card.py lays the card out at {inspect_card.W} x {inspect_card.H} units "
                         f"({inspect_card.W / u.scale:g} x {inspect_card.H / u.scale:g} px)")
    check_padding(cfg)
    check_anchoring(cfg)
    texts = {
        LAYOUT_REL / CONSTANTS_FILE: constants_layout(cfg),
        LAYOUT_REL / HERO_ROW_FILE: hero_row_layout(cfg),
        LAYOUT_REL / STAT_PANES_FILE: stat_panes_layout(cfg),
        LAYOUT_REL / INSPECT_FILE: inspect_card.layout(
            HeroCell(cfg).crop, XML_DECL + "<Desc>\n" + GENERATED,
            {t: cfg["top_backplate"][f"{t}_colour"] for t in ("blue", "red")}
            | {"neutral": cfg["element"]["inspect"]["neutral_colour"]},   # the card's team edge
            (u(rects(cfg)["inspect"][0][0]), u(rects(cfg)["inspect"][0][1])), 1 / u.scale,   # its place, for pixel-exact lines
            (*PLATES_AT, anchor_edges(cfg, "inspect")["t"])),   # where it's anchored, and its top from there
        LAYOUT_REL / MAPS_FILE: maps.layout(XML_DECL + "<Desc>\n" + GENERATED, PLATES_AT,
                                            {k: u(v) for k, v in panel_nudges(cfg).items()},
                                            minimap_bottoms(cfg),
                                            {k: (v - minimap_bottoms(cfg)[None], minimap_bottoms(cfg)[k] - minimap_bottoms(cfg)[None])
                                             for k, v in minimap_launch(cfg).items()},
                                            minimap_lifts(cfg)),
        LAYOUT_REL / INDEX_FILE: desc_index(layout_order(layout_dir, generated=GENERATED_LAYOUTS)),
    }
    return {rel: text.encode("utf-8") for rel, text in texts.items()} | texture_files(cfg)


def stale(cfg, source=SOURCE, files=None):
    """Generated files whose content on disk differs from what gen would write."""
    files = committed_files(cfg, source) if files is None else files

    def on_disk(rel):
        data = (source / rel).read_bytes()
        # git (core.autocrlf) may check text files out with CRLF; that isn't a change
        return data if rel.suffix == ".dds" else data.replace(b"\r\n", b"\n")

    return [rel for rel, data in files.items() if not (source / rel).is_file() or on_disk(rel) != data] \
        + orphans(files, source)


def orphans(files, source=SOURCE):
    """Generated textures on disk that gen no longer writes (superseded hashed versions)."""
    folder = source / TEXTURE_REL
    return sorted(p.relative_to(source) for p in folder.glob("FCJH_*.dds")
                  if p.relative_to(source) not in files) if folder.is_dir() else []


def write(cfg, source=SOURCE):
    files = committed_files(cfg, source)
    changed = stale(cfg, source, files)
    for rel in changed:
        path = source / rel
        if rel in files:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(files[rel])
        else:
            path.unlink()
    return changed


