def portrait_mask_file(team):
    # Heroes caches a texture by its path across replay reloads (layouts reload, textures
    # don't), so every version of a mask gets its own name: a hash of its content.
    digest = hashlib.sha1(portrait_mask(team)).hexdigest()[:8]
    return f"FCJH_Portrait_{team}_{digest}.dds"


@functools.cache
def portrait_mask(team, size=(256, 128), sub=4):
    """The portrait cut to the in-game cell's parallelogram, as an alpha mask.

    Blizzard's own ImageMaskTexture follows the portrait's TextureCoords, so cropping the
    observer's wide portrait art to its face also crops away the mask's left-edge cut (red
    portraits spilled over their neighbours). An AlphaMaskTexture spans the frame instead.
    Worked in native cell units, so it holds at any scale: the plate leans OVERLAP across
    its full height H - blue \\ (top edge on the left), red / (top edge on the right)."""
    w, h = size
    c = HeroCell
    top, bottom = -1, c.PORTRAIT_H - 1  # the portrait frame, in cell units
    # the portrait runs 2 units below the bar backings; Blizzard's art hides that strip,
    # ours showed the hero under the resource bar - so stop where the backing does
    # (1 unit early, so the mask's soft edge lands under the backing, not a hairline below it)
    cut = c.BLUE["health_backing"][3] - 1

    def left_edge(y):
        down = y / c.H
        return c.OVERLAP * (down if team == "blue" else 1 - down)

    rows = []
    for ty in range(h):
        row = bytearray()
        for tx in range(w):
            x0, x1 = tx / w * c.W, (tx + 1) / w * c.W
            cover = 0.0
            for s in range(sub):
                y = top + (ty + (s + 0.5) / sub) / h * (bottom - top)
                if y > cut:
                    continue
                left = left_edge(y) + c.BORDER
                right = left_edge(y) + c.W - c.OVERLAP - c.BORDER
                cover += max(0.0, min(x1, right) - max(x0, left)) / (x1 - x0)
            a = round(255 * cover / sub)
            row += bytes((a, a, a, a))  # B, G, R, A: grey = alpha, whichever the engine reads
        rows.append(bytes(row))
    return dds_bgra(w, h, b"".join(rows))


def slant_texture(team, cut, colour, alpha=255, size=(512, 32), sub=4):
    """A solid-colour parallelogram: the team's lean, cut `cut` of the width in (the slant's
    horizontal run over the bar's height, as a fraction of its width). Blue leans \\ (top edge
    flush left), red / (top edge flush right)."""
    w, h = size
    r, g, b = bytes.fromhex(colour)
    rows = []
    for ty in range(h):
        row = bytearray()
        for tx in range(w):
            cover = 0.0
            for s in range(sub):
                down = (ty + (s + 0.5) / sub) / h          # 0 at the top, 1 at the bottom
                shift = cut * (down if team == "blue" else 1 - down)
                left, right = shift * w, (1 - cut + shift) * w
                cover += max(0.0, min(tx + 1, right) - max(tx, left))
            row += bytes((b, g, r, round(alpha * cover / sub)))
        rows.append(bytes(row))
    return dds_bgra(w, h, b"".join(rows))


TOP_BACKPLATE_SIZE = (512, 256)    # px; drawn 1:1 at 1080p, centred on Blizzard's hexagon


def top_backplate_geometry(cfg):
    """The backplate's shapes in screen px: the wing band (a trapezoid along the top edge,
    its ends climbing with the plates' lean), Blizzard's hexagon, the hexagon padded out,
    and the texture box's top-left."""
    bp = cfg["top_backplate"]
    hexagon = [tuple(p) for p in bp["hexagon"]]
    left, right = hexagon[5], hexagon[2]           # the side points: where the wings meet it
    cx, cy = (left[0] + right[0]) / 2, (left[1] + right[1]) / 2
    padded = offset_polygon(hexagon, bp["padding"])
    lean = HeroCell(cfg).overlap / HeroCell(cfg).h
    rise = lean * cy
    bx = cfg["element"]["blue_level"]["rect"][0]
    rx, _, rw, _ = cfg["element"]["red_level"]["rect"]
    lb, rb = bx - bp["wing_margin"], rx + rw + bp["wing_margin"]
    wings = [(lb - rise, 0), (rb + rise, 0), (rb, cy), (lb, cy)]
    w, h = TOP_BACKPLATE_SIZE
    return {"hexagon": hexagon, "padded": padded, "wings": wings, "centre": cx,
            "box": (round(cx - w / 2), 0, w, h), "ends": (lb - rise, rb + rise)}


def offset_polygon(pts, d):
    """Grow a convex polygon outward by d px."""
    import math
    n = len(pts)
    cx, cy = sum(p[0] for p in pts) / n, sum(p[1] for p in pts) / n
    lines = []
    for i in range(n):
        (x1, y1), (x2, y2) = pts[i], pts[(i + 1) % n]
        dx, dy = x2 - x1, y2 - y1
        ln = math.hypot(dx, dy)
        nx, ny = dy / ln, -dx / ln
        if nx * (cx - x1) + ny * (cy - y1) > 0:     # point the normal away from the centre
            nx, ny = -nx, -ny
        lines.append(((x1 + nx * d, y1 + ny * d), (dx, dy)))
    out = []
    for i in range(n):
        (p, r), (q, s) = lines[i - 1], lines[i]
        t = ((q[0] - p[0]) * s[1] - (q[1] - p[1]) * s[0]) / (r[0] * s[1] - r[1] * s[0])
        out.append((p[0] + t * r[0], p[1] + t * r[1]))
    return out


def convex_sdf(pts):
    """Signed distance (px, negative inside) to a convex polygon, as a function of (x, y):
    exact along the edges, which is all the anti-aliasing needs."""
    import math
    n = len(pts)
    cx, cy = sum(p[0] for p in pts) / n, sum(p[1] for p in pts) / n
    edges = []
    for i in range(n):
        (x1, y1), (x2, y2) = pts[i], pts[(i + 1) % n]
        ln = math.hypot(x2 - x1, y2 - y1)
        nx, ny = (y2 - y1) / ln, -(x2 - x1) / ln
        if nx * (cx - x1) + ny * (cy - y1) > 0:
            nx, ny = -nx, -ny
        edges.append((nx, ny, nx * x1 + ny * y1))
    return lambda x, y: max(nx * x + ny * y - c for nx, ny, c in edges)


def top_backplate_texture(cfg):
    """The top bar's backplate (layout.toml [top_backplate]), drawn 1:1 at 1080p into a
    TOP_BACKPLATE_SIZE texture: stock dark, the team colour rising toward each wing's outer
    end, a hexagon lattice fading the same way, a sheen, the neutral plate round Blizzard's
    hexagon (only its padding shows; the hexagon is Blizzard's art on top), and a chrome rim
    round the whole outline. Anti-aliased from signed distances."""
    import math
    bp = cfg["top_backplate"]
    geo = top_backplate_geometry(cfg)
    x0, y0, w, h = geo["box"]
    cx = geo["centre"]
    lx, rx = geo["ends"]
    sd_wing, sd_hex = convex_sdf(geo["wings"]), convex_sdf(geo["padded"])
    bottom = max(y for _, y in geo["padded"])
    rgb = lambda hx: tuple(int(hx[i:i + 2], 16) / 255 for i in (0, 2, 4))
    mix = lambda a, b, t: tuple(p + (q - p) * t for p, q in zip(a, b))
    def ramp(stops, t):
        for (o1, c1), (o2, c2) in zip(stops, stops[1:]):
            if t <= o2:
                return mix(c1, c2, (t - o1) / (o2 - o1)) if isinstance(c1, tuple) else c1 + (c2 - c1) * (t - o1) / (o2 - o1)
        return stops[-1][1]
    stock = [rgb(c) for c in bp["stock"]]
    plate = [rgb(c) for c in bp["plate"]]
    chrome = list(zip((0, .35, .6, 1), (rgb(c) for c in bp["rim"])))
    team = {"blue": rgb(bp["blue_colour"]), "red": rgb(bp["red_colour"])}
    line = {k: mix(v, (1, 1, 1), .45) for k, v in team.items()}
    # colour along each wing: nothing beside the hexagon, full at the outer end
    fade = [tuple(p) for p in bp["fade"]]
    inner_l, inner_r = geo["hexagon"][5][0] + 10, geo["hexagon"][2][0] - 10
    R = bp["hex_px"] / 2
    r3 = math.sqrt(3)
    apothem = R * r3 / 2
    rim_half = bp["rim_width"] / 2
    clamp = lambda v: 0.0 if v < 0 else 1.0 if v > 1 else v
    rows = []
    for ty in range(h):
        y = y0 + ty + 0.5
        row = bytearray()
        if y > bottom + 3:
            rows.append(bytes(4 * w))
            continue
        vt = clamp(y / bottom)
        base = mix(*stock, vt)
        plate_c = mix(*plate, vt)
        rim_c = ramp(chrome, vt)
        sheen = bp["sheen"] * clamp(1 - y / (bottom / 2))
        for tx in range(w):
            x = x0 + tx + 0.5
            dw, dh = sd_wing(x, y), sd_hex(x, y)
            du = min(dw, dh)
            cover = clamp(0.5 - du)
            rim = clamp(rim_half + 0.5 - abs(du))
            if cover <= 0 and rim <= 0:
                row += b"\0\0\0\0"
                continue
            blue = x < cx
            t = clamp((x - inner_l) / (lx - inner_l) if blue else (x - inner_r) / (rx - inner_r))
            f = ramp(fade, t)
            side = "blue" if blue else "red"
            c = mix(base, team[side], bp["colour_alpha"] * f)
            if f > 0:   # the lattice: flat-topped hexagons, soft 1.5 px outlines, faint cells
                q, r = (2 / 3 * x) / R, (-1 / 3 * x + r3 / 3 * y) / R
                s_ = -q - r
                rq, rr, rs = round(q), round(r), round(s_)
                dq, dr, ds = abs(rq - q), abs(rr - r), abs(rs - s_)
                if dq > dr and dq > ds:
                    rq = -rr - rs
                elif dr > ds:
                    rr = -rq - rs
                hx, hy = R * 1.5 * rq, R * r3 * (rr + rq / 2)
                ox, oy = abs(x - hx), abs(y - hy)
                edge = max(oy / apothem, (ox + oy / r3) / R)
                outline = clamp((0.75 - (1 - edge) * apothem) / 0.75)
                c = mix(c, team[side], .22 * bp["lattice"] * f)
                c = mix(c, line[side], bp["lattice"] * f * outline)
            c = mix(c, (1, 1, 1), sheen)
            # the hexagon's neutral plate, with a fine light edge
            pc = clamp(0.5 - dh)
            if pc > 0:
                c = mix(c, plate_c, pc)
                c = mix(c, chrome[0][1], .6 * clamp(1 - abs(dh)))
            # the chrome rim, over everything, half outside the shape
            a = cover + rim * (1 - cover)
            c = mix(c, rim_c, rim / a if a else 0)
            row += bytes(round(v * 255) for v in (c[2], c[1], c[0], a))
        rows.append(bytes(row))
    return dds_bgra(w, h, b"".join(rows))


def bar_texture_size(w, h):
    """A slanted bar texture close to its size on screen (w x h px), in powers of two. Our
    DDS files carry no mipmaps, so a texture drawn much smaller than it is gets sampled
    coarsely and its slanted edge steps: the core bar (213 x 24 px) from a 512 x 32
    texture read "ragged" in game (2026-09-30)."""
    p2 = lambda v: 1 << max(4, (round(v) - 1).bit_length())
    return p2(w), p2(h)


def slant_bars(cfg):
    """Every generated texture but the portrait masks (bars, plate hit areas, the top
    backplate), by constant name: {name: (file name, dds bytes)}. Names
    carry a content hash (textures are cached by path across replay reloads)."""
    rects_ = team_bar_rects(cfg)
    lean = HeroCell(cfg).overlap / HeroCell(cfg).h
    xp, core = cfg["team_xp"], cfg["team_core"]
    out = {}
    # The bars' fills are STRETCHED to the value (seen in game, 2026-09-29: a draining core's
    # slanted ends squashed toward vertical), so a fill is a plain block of colour and the
    # slant comes from a mask over the bar (mask frames, AlphaMaskSiblings). Tracks don't
    # move, so they keep the slant in their own texture.
    for team in ("blue", "red"):
        for bar, spec, fill in (("xp", xp, xp["colour"]), ("core", core, core[f"{team}_colour"])):
            (_, _, w, h), _ = rects_[f"{team}_{bar}"]
            cut = lean * h / w
            size = bar_texture_size(w, h)
            for part, data in (("fill", slant_texture(team, 0, fill, size=(32, 32))),
                               ("track", slant_texture(team, cut, spec["track_colour"], spec["track_alpha"], size=size)),
                               ("mask", slant_texture(team, cut, "ffffff", size=size))):
                digest = hashlib.sha1(data).hexdigest()[:8]
                out[name(bar, part, team)] = (f"FCJH_Bar_{bar}_{part}_{team}_{digest}.dds", data)
        # XP for rows of 1-4 heroes: a shorter bar keeps the same slant only with its own cut
        for n in range(1, 5):
            (_, _, w, h), _ = team_bar_rects(cfg, n)[f"{team}_xp"]
            for part, colour, alpha in (("mask", "ffffff", 255), ("track", xp["track_colour"], xp["track_alpha"])):
                data = slant_texture(team, lean * h / w, colour, alpha, size=bar_texture_size(w, h))
                digest = hashlib.sha1(data).hexdigest()[:8]
                out[name("xp", part, team, f"n{n}")] = (f"FCJH_Bar_xp_{part}_{team}_n{n}_{digest}.dds", data)
    # the top bar's backplate behind Blizzard's hexagon (layout.toml [top_backplate])
    data = top_backplate_texture(cfg)
    digest = hashlib.sha1(data).hexdigest()[:8]
    out[name("top", "backplate")] = (f"FCJH_TopBackplate_{digest}.dds", data)
    cell = HeroCell(cfg)
    # the plate's own shape, as the click target's hit-test texture: plates overlap along the
    # slant, and a square click area sent clicks on one plate's corner to its neighbour
    for team in ("blue", "red"):
        data = bytearray(slant_texture(team, cell.overlap / cell.w, "ffffff", size=(256, 128)))
        # ...with the heroic icon cut away: a click there is for the heroic's tooltip
        # (talent_row_lifts), not a hero select
        l, t, r, b = heroic_icon_rect(cfg, team)
        for ty in range(round(t / cell.h * 128), min(128, round(b / cell.h * 128))):
            for tx in range(round(l / cell.w * 256), round(r / cell.w * 256)):
                data[128 + (ty * 256 + tx) * 4 + 3] = 0
        data = bytes(data)
        digest = hashlib.sha1(data).hexdigest()[:8]
        out[name("plate", "hit", team)] = (f"FCJH_PlateHit_{team}_{digest}.dds", data)
    return out


HEAL_BORDER = "FCJH_PopBorder_Heal.dds"   # the heal pop-up's frame (heal_popups)


def square_border(colour, size=64, edge=4):
    """A square outline in one colour, transparent inside: the heal pop-up's frame, in the
    spirit of the talent pop-up's team square."""
    r, g, b = bytes.fromhex(colour)
    rows = []
    for y in range(size):
        row = bytearray()
        for x in range(size):
            d = min(x, y, size - 1 - x, size - 1 - y)          # distance to the nearest edge
            a = 255 if d < edge else (90 if d < edge + 2 else 0)  # the line, then a faint inner glow
            row += bytes((b, g, r, a))
        rows.append(bytes(row))
    return dds_bgra(size, size, b"".join(rows))


