def fountain_rect(cfg, team):
    """The plate fountain's slot box in cell units (left, top, right, bottom), and the art's
    scale (cell units per slot unit)."""
    c = HeroCell(cfg)
    hv = FOUNTAIN_H * cfg["hero_row"]["scale"]   # visible height, cell units
    f = hv / SLOT_ART[3]                         # cell units per slot unit
    ax, ay, aw, _ = (v * f for v in SLOT_ART)
    cut = SLOT_LEAN * hv
    # on the health bar's black outline: the backing's top (on the bar itself it sat over the
    # outline, 3-4 px low: user, 2026-10-06 13:25; 1 up until 23_58_11, 1 px short of the
    # portrait's bottom: user). Down the edge moves it in by the lean, blue ~1 px
    bottom = c.team[team]["health_backing"][1]
    top = bottom - hv
    if team == "blue":
        # the outer end is the plate's left: its edge (HeroCell.edge) leans \; the slot leans
        # \ like it, its left side (l, top) -> (l + cut, bottom). The nearer corner rules.
        edge = c.edge
        left = max(edge(top), edge(bottom) - cut) + EDGE_INSET[team]
    else:
        # the right: its edge, mirrored, leans /; the slot leans /, its right
        # side (r, top) -> (r - cut, bottom)
        edge = lambda y: c.w - c.edge(y)
        left = min(edge(top), edge(bottom) + cut) - EDGE_INSET[team] - aw
    return (round(left - ax), round(top - ay), round(left - ax + SLOT_W * f), round(top - ay + SLOT_H * f)), f


