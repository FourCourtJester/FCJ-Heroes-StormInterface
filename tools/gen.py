"""
Generate layouts from layout.toml.

Committed output (written into src/, reviewed like any other file):
  FCJH_Constants.StormLayout   every layout.toml number, converted to layout units
  DescIndex.StormLayout        every layout in the folder, constants first

Dev-only output (staged at pack time, never committed, never shipped):
  FCJH_Dev.StormLayout         build stamp + in-game wireframe overlay

Layout units: the game lays its UI out on a grid ui_reference_height units tall, so at
1080p one unit is 0.9 px. layout.toml holds screen pixels; everything here converts.

    python tools/gen.py           # write generated files, list what changed
    python tools/gen.py --check   # exit 1 if any generated file is stale or hand-edited
"""

import argparse
import sys
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
CONFIG = REPO / "layout.toml"
SOURCE = REPO / "src" / "FCJH.StormInterface"
LAYOUT_REL = Path("Base.StormData") / "UI" / "Layout"

CONSTANTS_FILE = "FCJH_Constants.StormLayout"
INDEX_FILE = "DescIndex.StormLayout"
DEV_FILE = "FCJH_Dev.StormLayout"

XML_DECL = '<?xml version="1.0" encoding="utf-8" standalone="yes"?>\n'
GENERATED = ("<!-- GENERATED by tools/gen.py from layout.toml. Do not edit by hand:\n"
             "     change layout.toml (or tools/gen.py) and rebuild. -->\n")

# Hero cells read 1-5 on blue, then 6-0 on red.
BLUE_SLOTS = ["1", "2", "3", "4", "5"]
RED_SLOTS = ["6", "7", "8", "9", "0"]

KIND_COLORS = {  # A,R,G,B without the alpha, which comes from [dev] overlay_alpha
    "ui": "250,249,245",
    "obs": "242,166,90",
    "demand": "111,211,211",
}


def load_config(path=CONFIG):
    with open(path, "rb") as f:
        return tomllib.load(f)


class Units:
    """Pixel-to-layout-unit conversion for one screen configuration."""

    def __init__(self, cfg):
        screen = cfg["screen"]
        self.scale = screen["ui_reference_height"] / screen["height"]

    def __call__(self, px):
        return round(px * self.scale)


def name(*parts):
    return "FCJH_" + "_".join(str(p).upper() for p in parts)


def rects(cfg):
    """Every placed rectangle, (x, y, w, h) in px, by constant stem."""
    out = {}
    for key, el in cfg.get("element", {}).items():
        out[key] = (tuple(el["rect"]), el["kind"])
    row = cfg["hero_row"]
    step = row["cell_width"] + row["gap"]
    for team, left, slots in (("blue", row["blue_left"], BLUE_SLOTS), ("red", row["red_left"], RED_SLOTS)):
        for i, slot in enumerate(slots):
            out[f"hero_{slot}"] = ((left + i * step, row["top"], row["cell_width"], row["cell_height"]), "ui")
    return out


# ------------------------------------------------------------------ committed files

def constants_layout(cfg):
    u = Units(cfg)
    lines = []

    def const(n, v, comment=None):
        tail = f"  <!-- {comment} -->" if comment else ""
        lines.append(f'\t<Constant name="{n}" val="{v}"/>{tail}')

    lines.append("\t<!-- Screen -->")
    const(name("screen", "w"), u(cfg["screen"]["width"]), f'{cfg["screen"]["width"]} px')
    const(name("screen", "h"), u(cfg["screen"]["height"]), f'{cfg["screen"]["height"]} px')
    const(name("version"), cfg["meta"]["version"])

    lines.append("")
    lines.append("\t<!-- Elements: _L _T _R _B are edges measured from the screen's top-left (anchor")
    lines.append("\t     them to $GameUI pos=Min); _W _H are sizes. All in layout units. -->")
    for stem, ((x, y, w, h), kind) in rects(cfg).items():
        lines.append(f"\t<!-- {stem}: {kind}, px [{x}, {y}, {w}, {h}] -->")
        const(name(stem, "l"), u(x))
        const(name(stem, "t"), u(y))
        const(name(stem, "r"), u(x + w))
        const(name(stem, "b"), u(y + h))
        const(name(stem, "w"), u(w))
        const(name(stem, "h"), u(h))

    row = cfg["hero_row"]
    lines.append("")
    lines.append("\t<!-- Hero cell internals, measured from the cell's own top -->")
    const(name("hero", "portrait", "h"), u(row["portrait_height"]))
    const(name("hero", "hp", "t"), u(row["portrait_height"]))
    const(name("hero", "hp", "b"), u(row["portrait_height"] + row["hp_height"]))
    const(name("hero", "mana", "t"), u(row["portrait_height"] + row["hp_height"]))
    const(name("hero", "mana", "b"), u(row["portrait_height"] + row["hp_height"] + row["mana_height"]))
    const(name("hero", "popup", "size"), u(row["talent_popup_size"]))
    const(name("hero", "popup", "half"), u(row["talent_popup_size"] / 2))
    const(name("hero", "popup", "half", "neg"), -u(row["talent_popup_size"] / 2))

    return XML_DECL + GENERATED + "<Desc>\n" + "\n".join(lines) + "\n</Desc>\n"


def desc_index(layout_names):
    includes = "".join(f'\t<Include path="{(LAYOUT_REL / n).as_posix()}"/>\n' for n in layout_names)
    return XML_DECL + GENERATED + "<Desc>\n" + includes + "</Desc>\n"


def layout_order(layout_dir, extra=()):
    """Constants first, then the rest by name, then extras (dev layouts) last."""
    names = sorted(p.name for p in layout_dir.glob("*.StormLayout")
                   if p.name not in (INDEX_FILE, CONSTANTS_FILE))
    return [CONSTANTS_FILE] + names + list(extra)


def committed_files(cfg, source=SOURCE):
    """{path under source: text} for every generated file that lives in the repo."""
    layout_dir = source / LAYOUT_REL
    return {
        LAYOUT_REL / CONSTANTS_FILE: constants_layout(cfg),
        LAYOUT_REL / INDEX_FILE: desc_index(layout_order(layout_dir)),
    }


def stale(cfg, source=SOURCE):
    """Generated files whose content on disk differs from what gen would write."""
    out = []
    for rel, text in committed_files(cfg, source).items():
        path = source / rel
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            out.append(rel)
    return out


def write(cfg, source=SOURCE):
    changed = stale(cfg, source)
    for rel, text in committed_files(cfg, source).items():
        if rel in changed:
            path = source / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    return changed


# ------------------------------------------------------------------ dev-only files

def dev_layout(cfg, stamp):
    """Build stamp and wireframe overlay, as an override of GameUI."""
    dev = cfg.get("dev", {})
    u = Units(cfg)
    sx, sy = dev.get("build_stamp", [16, 16])
    parts = [
        '\t\t<Frame type="Label" name="FCJH_DevStamp">',
        f'\t\t\t<Anchor side="Top" relative="$parent" pos="Min" offset="{u(sy)}"/>',
        f'\t\t\t<Anchor side="Left" relative="$parent" pos="Min" offset="{u(sx)}"/>',
        '\t\t\t<Style val="WaitingForPlayersDialogChat"/>',
        '\t\t\t<Text val="#FCJH_DEV_STAMP"/>',
        '\t\t\t<Unclipped val="true"/>',
        '\t\t\t<Options val="NoWrapping"/>',
        '\t\t\t<AcceptsMouse val="false"/>',
        '\t\t</Frame>',
    ]
    if dev.get("wireframe_overlay"):
        alpha = dev.get("overlay_alpha", 60)
        parts += [
            '\t\t<Frame type="Frame" name="FCJH_DevWireframe">',
            '\t\t\t<Anchor relative="$parent"/>',
            '\t\t\t<AcceptsMouse val="false"/>',
        ]
        for stem, ((x, y, w, h), kind) in rects(cfg).items():
            parts += [
                f'\t\t\t<Frame type="Image" name="FCJH_Wire_{stem}">',
                f'\t\t\t\t<Anchor side="Top" relative="$parent" pos="Min" offset="#{name(stem, "t")}"/>',
                f'\t\t\t\t<Anchor side="Left" relative="$parent" pos="Min" offset="#{name(stem, "l")}"/>',
                f'\t\t\t\t<Anchor side="Bottom" relative="$parent" pos="Min" offset="#{name(stem, "b")}"/>',
                f'\t\t\t\t<Anchor side="Right" relative="$parent" pos="Min" offset="#{name(stem, "r")}"/>',
                '\t\t\t\t<Texture val="@UI/PauseScreenDimImage"/>',
                '\t\t\t\t<ColorAdjustMode val="Fill"/>',
                f'\t\t\t\t<AdjustmentColor val="{alpha},{KIND_COLORS[kind]}"/>',
                '\t\t\t\t<AcceptsMouse val="false"/>',
                '\t\t\t</Frame>',
            ]
        parts.append('\t\t</Frame>')
    body = "\n".join(parts)
    return (XML_DECL + "<!-- Dev build only: staged by tools/pack.py, never committed or shipped. -->\n"
            "<Desc>\n"
            f'\t<Constant name="FCJH_DEV_STAMP" val="{stamp}"/>\n'
            '\t<Frame type="GameUI" name="GameUI" file="GameUI">\n'
            f"{body}\n"
            "\t</Frame>\n"
            "</Desc>\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()
    cfg = load_config()
    if args.check:
        bad = stale(cfg)
        for rel in bad:
            print(f"stale: {rel.as_posix()} (run python tools/gen.py)")
        return 1 if bad else 0
    changed = write(cfg)
    print("\n".join(f"wrote {rel.as_posix()}" for rel in changed) or "generated files up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
