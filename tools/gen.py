class Units:
    """Pixel-to-layout-unit conversion for one screen configuration."""

    def __init__(self, cfg):
        screen = cfg["screen"]
        self.scale = screen["ui_reference_height"] / screen["height"]

    def __call__(self, px):
        return round(px * self.scale)


def name(*parts):
    return "FCJH_" + "_".join(str(p).upper() for p in parts)


def rects(cfg):
    """Every placed rectangle, (x, y, w, h) in px, by constant stem."""
    out = {}
    for key, el in cfg.get("element", {}).items():
        out[key] = (tuple(el["rect"]), el["kind"])
    px = 1 / Units(cfg).scale  # hero cells are laid out in layout units; these are exact
    row = cfg["hero_row"]
    cell = HeroCell(cfg)
    for team, left, slots in (("blue", row["blue_left"], BLUE_SLOTS), ("red", row["red_left"], RED_SLOTS)):
        for i, slot in enumerate(slots):
            out[f"hero_{slot}"] = ((round(left + i * cell.pitch * px, 1), row["top"],
                                    round(cell.w * px, 1), round(cell.h * px, 1)), "ui")
    out.update(team_bar_rects(cfg))
    return out


# Blizzard's core health bar: fixed at 237 x 27 units (stormobserverpanel Team1/2CoreUnitStatus
# HealthBar). Never resized, only moved; our cut is drawn inside it.
CORE_BAR_W, CORE_BAR_H = 237, 27


def team_bar_rects(cfg, n=5):
    """The bars stacked on each hero row: team XP on the plates' top edge, core health on
    top of that. Both are parallelograms continuing the row's slanted outer edges, so each
    bar's rect here is its bounding box and its slant is `lean` px per px of height.
    XP runs the full top edge; core sits at the row's inner end (toward the minimap).
    n: heroes per team. With fewer than 5 the rows pack toward the minimap (blue's plates
    shift inward - FCJH_RowPacker), so XP spans only those n plates."""
    row, px = cfg["hero_row"], 1 / Units(cfg).scale
    cell = HeroCell(cfg)
    lean = cell.overlap / cell.h                       # the plates' slant, px across per px up
    edge = ((n - 1) * cell.pitch + cell.w - cell.overlap) * px   # the row's top edge
    shift = (5 - n) * cell.pitch * px                  # blue's plates move this far inward
    top = row["top"]
    xp, core = cfg["team_xp"], cfg["team_core"]
    xp_bottom = top - xp["gap"]
    xp_top = xp_bottom - xp["height"]
    core_w, core_h = CORE_BAR_W * px, CORE_BAR_H * px
    core_bottom = xp_top - core["gap"]
    core_top = core_bottom - core_h
    out = {}
    # the row's outer edges, as x at height y: blue leans \ (its top edge starts at the
    # row's left), red leans / (one overlap in)
    blue_l = lambda y: row["blue_left"] + shift - lean * (top - y)
    red_l = lambda y: row["red_left"] + cell.overlap * px + lean * (top - y)
    r1 = lambda v: round(v, 1)
    out["blue_xp"] = ((r1(blue_l(xp_top)), r1(xp_top), r1(edge + lean * xp["height"]), xp["height"]), "ui")
    out["red_xp"] = ((r1(red_l(xp_bottom)), r1(xp_top), r1(edge + lean * xp["height"]), xp["height"]), "ui")
    out["blue_core"] = ((r1(blue_l(core_bottom) + edge - core_w), r1(core_top), r1(core_w), r1(core_h)), "ui")
    out["red_core"] = ((r1(red_l(core_bottom)), r1(core_top), r1(core_w), r1(core_h)), "ui")
    return out


class HeroCell:
    """Blizzard's in-game top-bar hero cell, rebuilt and scaled by [hero_row] scale.

    Source: core partyframe.stormlayout - HeroOverviewTemplate (blue), HeroOverviewTemplate_R
    (red), HeroUnitStatusNoHealthTemplate / HeroUnitStatusTemplate (the bars), and
    PartyFrameOverview/Team1HeroOverview (the stacking). The slanted look lives in Blizzard's
    art (HUD_TopBar_Team_HeroFrame*), drawn for exactly these numbers, so the NATIVE numbers
    below are Blizzard's, not ours: layout units, x from the cell's left, y from its top.
    Red is blue mirrored. Every piece is pinned on all four sides, so the art stretches.
    """

    W, H = 128, 61
    OVERLAP = 30                # HeroStackShift: each cell overlaps the next by 30
    PORTRAIT_H = 56             # 128 x 56, one unit above the cell's top
    # The frame art's black border along each slanted edge is ~3 units wide and draws UNDER
    # the portrait; portraits stop this far short of the edge so it shows between heroes.
    BORDER = 2
    # (left, top, right, bottom)
    BLUE = {
        "health_backing": (21, 36, 126, 53),    # status frame 105 wide, 2 in from the right
        "health": (24, 38, 121, 46),            # 97 x 8, backing +2 down, 5 in from its right
        "mana_backing": (26, 46, 127, 53),      # backing's left +5 .. right +1, bottom-aligned;
                                                # Blizzard leaves its height to the art: 7 is ours
        "energy": (30, 48, 125, 52),            # 95 x 4, 2 under health, 6 in from its left
    }
    RED = {
        "health_backing": (2, 36, 107, 53),
        "health": (8, 38, 105, 46),             # 2 in from the backing's right
        "mana_backing": (2, 46, 102, 53),       # backing's left .. right -5
        "energy": (4, 48, 99, 52),              # 4 left of the health bar
    }
    # Blizzard's death timer spans IconFrame +15 .. -10: centred 2.5 right of the middle
    DEATH_SHIFT = 2.5
    # Crowd control text ("STUNNED"...): a band across the bottom of the portrait, just
    # above the health backing (36). Ours, not Blizzard's - their cell shows no CC.
    CC_BAND = (22, 36)
    # ...and its icon, a square centred where the death timer is: (unused, unused, half-width)
    CC_ICON = (2, 20, 9)
    # Fountain-ready marker: a small square in the plate's top corner on the portrait side,
    # away from the slant (left on blue, right on red). (left, top, right, bottom)
    FOUNTAIN = {"blue": (8, 2, 24, 18), "red": (104, 2, 120, 18)}
    # Heroic token: the corner opposite the fountain, just above the bars (36), clear of the
    # slanted edge; a parallelogram leaning with the plate (our mask). Its size comes from
    # layout.toml ([hero_row] heroic_token); it grows from this fixed corner - bottom-right
    # on blue, bottom-left on red (x, y).
    HEROIC_CORNER = {"blue": (111, 34), "red": (17, 34)}
    # The observer's portrait art is wide with the face on the right; Blizzard's observer
    # crops [0.1, 0.45, 0.65, 1.0] into 165 x 60, i.e. the art is 2.75x as wide as tall per
    # unit of crop. Same top/bottom/right here, left worked out for this cell's shape.
    ART_ASPECT, CROP_TOP, CROP_BOTTOM = 2.75, 0.1, 0.65

    def __init__(self, cfg):
        k = cfg["hero_row"]["scale"]
        s = lambda v: round(v * k)
        self.w, self.h = s(self.W), s(self.H)
        self.pitch = s(self.W - self.OVERLAP)
        self.overlap = self.w - self.pitch
        self.portrait_top, self.portrait_bottom = s(-1), s(self.PORTRAIT_H - 1)
        self.team = {team: {part: tuple(s(v) for v in rect) for part, rect in g.items()}
                     for team, g in (("blue", self.BLUE), ("red", self.RED))}
        self.death_shift = s(self.DEATH_SHIFT)
        # the death timer's label spans 2 .. h-1 of the cell, text centred: its middle
        self.death_mid = round((2 + self.h - 1) / 2)
        self.cc_band = tuple(s(v) for v in self.CC_BAND)
        self.cc_icon = tuple(s(v) for v in self.CC_ICON)
        self.fountain = {t: tuple(s(v) for v in r) for t, r in self.FOUNTAIN.items()}
        tw, th = (Units(cfg)(v) for v in cfg["hero_row"]["heroic_token"])
        bx, by = (s(v) for v in self.HEROIC_CORNER["blue"])
        rx, ry = (s(v) for v in self.HEROIC_CORNER["red"])
        self.heroic = {"blue": (bx - tw, by - th, bx, by), "red": (rx, ry - th, rx + tw, ry)}
        # the heroic's icon is square: cut top and bottom to the token's shape
        self.heroic_crop = round(max(0.0, (1 - th / tw) / 2), 3)
        across = self.W / self.PORTRAIT_H * (self.CROP_BOTTOM - self.CROP_TOP) / self.ART_ASPECT
        self.crop = (self.CROP_TOP, round(1 - across, 3), self.CROP_BOTTOM, 1.0)


def dds_bgra(w, h, pixels):
    """An uncompressed 32-bit DDS (A8R8G8B8), no mipmaps."""
    import struct
    pf = struct.pack("<8I", 32, 0x41, 0, 32, 0x00FF0000, 0x0000FF00, 0x000000FF, 0xFF000000)
    header = struct.pack("<7I", 124, 0x100F, h, w, w * 4, 0, 0) + b"\0" * 44 + pf \
        + struct.pack("<5I", 0x1000, 0, 0, 0, 0)
    return b"DDS " + header + pixels


